"""Application settings loaded from environment / backend/.env (never hard-coded)."""
from functools import lru_cache
from pathlib import Path

from cryptography.fernet import Fernet
from pydantic import Field, model_validator
from pydantic_settings import BaseSettings, SettingsConfigDict

_ENV_FILE = Path(__file__).resolve().parent.parent / ".env"

# Environments in which relaxed (local, plain-HTTP) settings are tolerated.
RELAXED_ENVIRONMENTS = frozenset({"dev", "test"})
_WEAK_SECRETS = frozenset({"changeme", "change-me", "secret", "password", "dev", "test", "default"})


class Settings(BaseSettings):
    """Runtime configuration. Values come from backend/.env (generated by scripts/gen_env.sh).

    Defaults are secure: outside ``dev`` and ``test`` the application refuses to start with
    a weak secret, an invalid Fernet key, an insecure session cookie or wildcard CORS.
    """

    model_config = SettingsConfigDict(env_file=str(_ENV_FILE), extra="ignore")

    DATABASE_URL: str
    TEST_DATABASE_URL: str | None = None
    SECRET_KEY: str
    FERNET_KEY: str
    APP_TIMEZONE: str = "Europe/Amsterdam"
    CORS_ORIGINS: str = "http://localhost:3000"
    # Secure default: anything other than dev/test is treated as production.
    APP_ENV: str = "production"
    # None means "derive": secure everywhere except dev and test.
    COOKIE_SECURE: bool | None = None
    SESSION_TTL_HOURS: int = Field(12, ge=1)
    # Offline capture policy (DEC-05).
    OFFLINE_MAX_AGE_HOURS: int = Field(48, ge=1)
    ONLINE_SKEW_SECONDS: int = Field(30, ge=0)
    FUTURE_TOLERANCE_SECONDS: int = Field(60, ge=0)
    # Login throttle (DEC-10).
    LOGIN_MAX_FAILURES: int = Field(5, ge=1)
    LOGIN_LOCK_MINUTES: int = Field(15, ge=1)
    # Synthetic seed passwords: no literal defaults; scripts/gen_env.sh generates them.
    SEED_ADMIN_PASSWORD: str | None = None
    SEED_SUPERVISOR_PASSWORD: str | None = None
    SEED_HR_PASSWORD: str | None = None

    @property
    def relaxed(self) -> bool:
        """True in the dev and test environments only."""
        return self.APP_ENV in RELAXED_ENVIRONMENTS

    @model_validator(mode="after")
    def _enforce_secure_configuration(self) -> "Settings":
        """Derive the cookie default and reject insecure configuration outside dev/test."""
        if self.COOKIE_SECURE is None:
            self.COOKIE_SECURE = not self.relaxed
        if self.relaxed:
            return self
        problems: list[str] = []
        if len(self.SECRET_KEY) < 32 or self.SECRET_KEY.strip().lower() in _WEAK_SECRETS:
            problems.append("SECRET_KEY must be a random value of at least 32 characters")
        try:
            Fernet(self.FERNET_KEY.encode())
        except (ValueError, TypeError):
            problems.append("FERNET_KEY must be a valid urlsafe-base64 32-byte Fernet key")
        if not self.COOKIE_SECURE:
            problems.append("COOKIE_SECURE must be true outside dev and test")
        if "*" in [o.strip() for o in self.CORS_ORIGINS.split(",")]:
            problems.append("CORS_ORIGINS must not contain a wildcard outside dev and test")
        if problems:
            raise ValueError("Insecure configuration for APP_ENV=%r: %s" % (self.APP_ENV, "; ".join(problems)))
        return self


# PUBLIC_INTERFACE
@lru_cache
def get_settings() -> Settings:
    """Return the cached application settings."""
    return Settings()
